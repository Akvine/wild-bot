package ru.akvine.wild.bot.infrastructure.outbox;

/**
 * Доставляет сообщения одного типа получателю (бот, внешний сервис). Доставка гарантируется «минимум
 * один раз»: если приложение упало после отправки, но до пометки «доставлено», сообщение будет отправлено
 * ещё раз - поэтому обработчик по возможности должен быть идемпотентным. Исключение из {@link #handle}
 * означает неудачу: сообщение будет повторено позже с нарастающей паузой.
 */
public interface OutboxHandler {

    /**
     * @return тип сообщений, которые обрабатывает этот обработчик
     */
    String type();

    void handle(OutboxMessage message) throws Exception;
}
