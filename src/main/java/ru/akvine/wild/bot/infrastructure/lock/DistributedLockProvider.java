package ru.akvine.wild.bot.infrastructure.lock;

import java.util.concurrent.Callable;
import java.util.concurrent.TimeUnit;

/**
 * Интерфейс распределённой блокировки для синхронизации доступа к общим ресурсам.
 * Блокировка идентифицируется уникальным строковым ключом.
 * Методы lock автоматически захватывают и освобождают блокировку вокруг выполнения задачи.
 * tryLock пытается захватить блокировку без длительного ожидания, возвращая false при неудаче.
 * unlock служит для ручного освобождения ранее захваченной блокировки.
 */
public interface DistributedLockProvider {

    /**
     * Выполняет задачу, возвращающую результат, под защитой распределённой блокировки.
     * Если блокировка с указанным идентификатором уже удерживается другим участником,
     * метод блокируется до тех пор, пока блокировка не будет освобождена.
     *
     * @param lockId уникальный идентификатор блокировки
     * @param job    задача, выполняемая под защитой блокировки и возвращающая результат
     * @param <T>    тип возвращаемого значения
     * @return результат выполнения задачи
     * @throws RuntimeException если задача выбрасывает исключение или возникает ошибка при работе с блокировкой
     */
    <T> T lock(String lockId, Callable<T> job);

    /**
     * Выполняет задачу, возвращающую результат, под защитой распределённой блокировки,
     * ожидая её получения не дольше указанного времени.
     *
     * @param lockId   уникальный идентификатор блокировки
     * @param job      задача, выполняемая под защитой блокировки и возвращающая результат
     * @param timeout  максимальное время ожидания блокировки
     * @param timeUnit единица измерения времени ожидания
     * @param <T>      тип возвращаемого значения
     * @return результат выполнения задачи
     * @throws RuntimeException если задача выбрасывает исключение, блокировка не получена за отведённое время
     *                          или возникает другая ошибка при работе с блокировкой
     */
    <T> T lock(String lockId, Callable<T> job, long timeout, TimeUnit timeUnit);

    /**
     * Выполняет задачу без возвращаемого значения под защитой распределённой блокировки.
     * <p>
     * Если блокировка с идентификатором {@code lockId} уже удерживается другим участником,
     * метод будет ожидать её освобождения без ограничения по времени.
     *
     * @param lockId   уникальный идентификатор блокировки
     * @param runnable задача, выполняемая под защитой блокировки
     * @throws RuntimeException если задача выбрасывает исключение или возникает ошибка при работе с блокировкой
     */
    void lock(String lockId, Runnable runnable);

    /**
     * Выполняет задачу без возвращаемого значения под защитой распределённой блокировки,
     * ожидая её получения не дольше указанного времени.
     *
     * @param lockId   уникальный идентификатор блокировки
     * @param runnable задача, выполняемая под защитой блокировки
     * @param timeout  максимальное время ожидания блокировки
     * @param timeUnit единица измерения времени ожидания
     * @throws RuntimeException если задача выбрасывает исключение, блокировка не получена за отведённое время
     *                          или возникает другая ошибка при работе с блокировкой
     */
    void lock(String lockId, Runnable runnable, long timeout, TimeUnit timeUnit);

    /**
     * Пытается немедленно получить распределённую блокировку и выполнить задачу.
     * <p>
     * Если блокировка свободна, метод захватывает её, выполняет {@code job} и освобождает блокировку,
     * возвращая {@code true}. Если блокировка уже удерживается другим участником, метод не ждёт
     * и сразу возвращает {@code false}, не выполняя задачу.
     *
     * @param lockId уникальный идентификатор блокировки
     * @param job    задача, выполняемая под защитой блокировки
     * @return {@code true}, если блокировка была успешно захвачена и задача выполнена;
     *         {@code false}, если блокировка уже удерживается другим участником
     * @throws RuntimeException если задача выбрасывает исключение или возникает ошибка при работе с блокировкой
     */
    boolean tryLock(String lockId, Runnable job);

    /**
     * Пытается получить распределённую блокировку в течение указанного времени и выполнить задачу.
     * <p>
     * Если блокировка свободна или освобождается до истечения таймаута, метод захватывает её,
     * выполняет {@code job}, освобождает блокировку и возвращает {@code true}.
     * Если за отведённое время блокировка не получена, метод возвращает {@code false}, не выполняя задачу.
     *
     * @param lockId   уникальный идентификатор блокировки
     * @param job      задача, выполняемая под защитой блокировки
     * @param timeout  максимальное время ожидания блокировки
     * @param timeUnit единица измерения времени ожидания
     * @return {@code true}, если блокировка была успешно захвачена и задача выполнена;
     *         {@code false}, если блокировка не была получена за отведённое время
     * @throws RuntimeException если задача выбрасывает исключение или возникает ошибка при работе с блокировкой
     */
    boolean tryLock(String lockId, Runnable job, long timeout, TimeUnit timeUnit);

    /**
     * Освобождает распределённую блокировку с указанным идентификатором.
     * <p>
     * Метод должен вызываться только в том случае, если блокировка была захвачена текущим участником
     * (например, через ручное управление). Поведение при попытке снять чужую блокировку зависит
     * от реализации и может привести к исключению или быть проигнорированным.
     *
     * @param key идентификатор блокировки, которую необходимо освободить
     * @throws RuntimeException если блокировка не удерживается текущим участником или возникает ошибка при её снятии
     */
    void unlock(String key);
}
