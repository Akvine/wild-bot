package ru.akvine.wild.bot.infrastructure.retry;

import java.util.function.Supplier;

/**
 * Интерфейс исполнителя задач с автоматическим повтором при возникновении исключений.
 * <p>
 * Реализации этого интерфейса определяют стратегию повторов: количество попыток,
 * величину задержки между ними и политику её изменения.
 */
public interface RetryExecutor {

    /**
     * Выполняет задачу {@link Runnable} с повторными попытками.
     * <p>
     * Если задача завершается успешно (без исключения), метод должен немедленно завершиться.
     * При возникновении исключения выполняются повторные попытки с задержкой между ними.
     * Если все попытки исчерпаны, выбрасывается либо последнее возникшее исключение,
     * либо исключение, переданное в параметре {@code throwIfAttemptsCountExceeded} —
     * конкретное поведение зависит от реализации.
     *
     * @param task                         задача для выполнения
     * @param throwIfAttemptsCountExceeded исключение, которое может быть выброшено,
     *                                     если все попытки завершились неудачей
     * @throws RuntimeException если задача не была выполнена успешно за отведённое число попыток
     */
    void execute(Runnable task, RuntimeException throwIfAttemptsCountExceeded);

    /**
     * Выполняет задачу {@link Supplier}, возвращающую результат, с повторными попытками.
     * <p>
     * Поведение аналогично {@link #execute(Runnable, RuntimeException)}, но при успешном
     * выполнении возвращает значение, полученное от поставщика.
     *
     * @param task                         поставщик результата
     * @param throwIfAttemptsCountExceeded исключение, которое может быть выброшено,
     *                                     если все попытки завершились неудачей
     * @param <T>                          тип возвращаемого значения
     * @return результат успешного выполнения задачи
     * @throws RuntimeException если задача не была выполнена успешно за отведённое число попыток
     */
    <T> T execute(Supplier<T> task, RuntimeException throwIfAttemptsCountExceeded);
}
