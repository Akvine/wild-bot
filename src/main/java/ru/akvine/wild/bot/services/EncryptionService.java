package ru.akvine.wild.bot.services;

/**
 * Интерфейс для шифрования и дешифрования.
 * <p>
 * Этот сервис предоставляет симметричное шифрование и расшифровку строк.
 * Все данные преобразуются в шестнадцатеричное
 * представление (HexString), чтобы упростить хранение и передачу.
 */
public interface EncryptionService {

    /**
     * Расшифровывает строку, зашифрованную алгоритмом ChaCha20.
     * <p>
     * Ожидается, что входная строка была получена путём шифрования методом {@link #encrypt(String)}.
     *
     * @param encryptedHex зашифрованная строка в формате HEX (HexString), полученная от {@code encrypt()}
     * @return исходная строка в расшифрованном виде
     */
    String decrypt(String encryptedHex);

    /**
     * Шифрует текстовую строку с использованием ChaCha20 и возвращает HEX-представление.
     * <p>
     * Один и тот же входной текст всегда даст один и тот же зашифрованный результат при фиксированном IV и ключе.
     *
     * @param plainText исходная строка для шифрования
     * @return зашифрованная строка в формате HEX (HexString)
     */
    String encrypt(String plainText);
}
